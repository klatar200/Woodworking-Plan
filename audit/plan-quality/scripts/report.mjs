// report.mjs — Stage 8: generate the audit's numbers and decision lists from the records.
// Writes the block between the stage8 markers in REPORT.md and the full lists to decision-lists.md.
// Deterministic: same records in, same text out.
//   node audit/plan-quality/scripts/report.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const DIR = 'audit/plan-quality/plans';
const REPORT = 'audit/plan-quality/REPORT.md';
const LISTS = 'audit/plan-quality/decision-lists.md';
const NAMES = {
  R1: 'depends on content we don\'t have', R2: 'part not in the cut list', R3: 'cut row not a real used part',
  R4: 'part size not from a listed material', R5: 'materials don\'t cover the cut list',
  R6: 'fastener/hardware missing or contradictory', R8: 'build order impossible',
  R9: 'pocket-hole jig setting not stated', R10: 'position not given', R11: '"as shown" with nothing shown',
  R14: 'steps, cut list and materials disagree',
};
const ORDER = Object.keys(NAMES);
const short = (t, n = 150) => { const s = String(t || '').replace(/\s+/g, ' ').trim(); return s.length > n ? `${s.slice(0, n - 1)}…` : s; };
const bump = (o, k, by = 1) => { o[k] = (o[k] || 0) + by; };

const recs = readdirSync(DIR).sort().map((f) => JSON.parse(readFileSync(`${DIR}/${f}`, 'utf8')));
const verdicts = {}; const failPlans = {}; const failLevel = {}; const unknowns = {};
const fixBy = {}; const unpublish = []; const human = []; const shipU = [];
let consumable = 0; let otherGaps = 0; let kerfOnly = 0; let importAffected = 0; let overrides = 0;

for (const r of recs) {
  bump(verdicts, r.verdict);
  if (r.importAffected) importAffected++;
  if (r.override) overrides++;
  const gaps = r.gaps || [];
  if (gaps.some((g) => g.kind === 'consumable')) consumable++;
  if (gaps.some((g) => g.kind !== 'consumable')) otherGaps++;
  if (r.checks.R5?.kerfOnly) kerfOnly++;
  const fails = Object.entries(r.checks).filter(([, c]) => c.result === 'fail' && c.cause !== 'import');
  for (const [id, c] of fails) { bump(failPlans, id); bump(failLevel, `${id} ${c.level}`); }
  for (const [id, c] of Object.entries(r.checks)) if (c.result === 'unknown') bump(unknowns, id);
  const counted = fails.filter(([id]) => id !== 'R9');
  if (r.verdict.startsWith('Unpublish')) {
    let why;
    if (r.override) why = `Keagan: ${r.override.reason}`;
    else {
      const up = new Set(r.verifier?.upheld || []);
      const u = counted.find(([id, c]) => c.level === 'Unpublish' && c.confidence === 'certain' && up.has(id));
      why = u ? `${u[0]}: ${short(r.verifier?.notes?.[u[0]] || u[1].reason || u[1].evidence?.[0]?.quote)}`
        : `${counted.filter(([, c]) => c.confidence === 'certain').map(([id]) => id).join(', ')} (4+ certain Fix, verifier-upheld)`;
    }
    unpublish.push(`| [${r.slug}](https://notchplans.com/plans/${r.slug}) | ${why.replace(/\|/g, '/')} |`);
  } else if (r.verdict.startsWith('Fix')) {
    for (const [id] of counted) (fixBy[id] ||= []).push(r.slug);
  } else if (r.verdict.startsWith('Ship (unverified)')) {
    shipU.push(`${r.slug} (${Object.entries(r.checks).filter(([id, c]) => c.result === 'unknown' && id !== 'R9').map(([id]) => id).join(', ')})`);
  }
  if (r.verdict.includes('Human review')) {
    const why = r.humanReview || `unknown on ${['R1', 'R2', 'R8'].filter((id) => r.checks[id]?.result === 'unknown').join('/')}`;
    human.push(`| ${r.slug} | ${r.verdict} | ${short(why).replace(/\|/g, '/')} |`);
  }
}

const vOrder = ['Unpublish', 'Fix', 'Fix + Human review', 'Ship (unverified)', 'Ship (unverified) + Human review', 'Ship'];
const lines = [];
lines.push('<!-- stage8:begin (generated by scripts/report.mjs — do not edit by hand) -->', '');
lines.push(`### Headline (${recs.length} published plans, rubric R-2)`, '', '| Verdict | Plans |', '|---|---|');
for (const v of vOrder) if (verdicts[v]) lines.push(`| ${v} | ${verdicts[v]} |`);
for (const [v, n] of Object.entries(verdicts)) if (!vOrder.includes(v)) lines.push(`| ${v} | ${n} |`);
lines.push('', `Unpublish rate ${(100 * (verdicts.Unpublish || 0) / recs.length).toFixed(1)}%. ${overrides} verdict(s) are Keagan's own call (\`override\`).`, '');
lines.push('### Failures by check (plans failing, `cause: "plan"`)', '', '| Check | What | Plans | Unpublish-level | Fix-level |', '|---|---|---|---|---|');
for (const id of [...ORDER].sort((a, b) => (failPlans[b] || 0) - (failPlans[a] || 0))) {
  if (!failPlans[id]) continue;
  const note = id === 'R9' ? ' (recorded only; not counted)' : '';
  lines.push(`| ${id} | ${NAMES[id]}${note} | ${failPlans[id]} | ${failLevel[`${id} Unpublish`] || 0} | ${failLevel[`${id} Fix`] || 0} |`);
}
lines.push('', '### Catalog-wide items (one bulk fix each, not per-plan verdicts)', '');
lines.push(`- **Importer damage:** ${importAffected} plans carry import-damaged measurements (Stage 2, \`import-fidelity.md\`).`);
lines.push(`- **R9 jig setting:** ${failPlans.R9 || 0} plans name pocket-hole screws but no jig thickness setting.`);
lines.push(`- **Consumables missing from materials** (glue, tape, finish…): ${consumable} plans (\`gaps\` kind consumable).`);
lines.push(`- **Kerf-only stock shortfalls** (≤ 1/2″): ${kerfOnly} plans (R5 \`kerfOnly\`).`);
lines.push(`- **Other problems no check covers:** ${otherGaps} plans carry \`gaps\` entries (per-plan, in the records).`, '');
lines.push('### `unknown` per check (all 610)', '', '| Check | Unknown |', '|---|---|');
for (const id of ORDER) if (unknowns[id]) lines.push(`| ${id} | ${unknowns[id]} |`);
lines.push('', `### Unpublish (${unpublish.length})`, '', '| Plan | Why |', '|---|---|', ...unpublish);
lines.push('', `### Human review (${human.length})`, '', '| Plan | Verdict | Why |', '|---|---|---|', ...human);
lines.push('', `Fix (grouped by fix type) and Ship (unverified) lists: [\`decision-lists.md\`](decision-lists.md).`, '', '<!-- stage8:end -->');

const block = lines.join('\n');
const rep = readFileSync(REPORT, 'utf8');
const re = /<!-- stage8:begin[\s\S]*?<!-- stage8:end -->/;
writeFileSync(REPORT, re.test(rep) ? rep.replace(re, block) : `${rep.trimEnd()}\n\n## Stage 8 — results\n\n${block}\n`);

const out = ['# Plan-quality audit — decision lists (generated by `scripts/report.mjs`)', '',
  'A Fix plan appears under every check it fails (R9 excluded). Per-plan evidence: `plans/<slug>.json`.', ''];
for (const id of ORDER) {
  if (!fixBy[id]) continue;
  out.push(`## ${id} — ${NAMES[id]} (${fixBy[id].length} Fix plans)`, '', fixBy[id].join(', '), '');
}
out.push(`## Ship (unverified) (${shipU.length}) — no failure; unknown checks in brackets`, '', shipU.join(', '), '');
writeFileSync(LISTS, out.join('\n'));
console.log(JSON.stringify({ verdicts, unpublish: unpublish.length, human: human.length }, null, 1));
